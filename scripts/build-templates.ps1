<#
.SYNOPSIS
  Builds the self-contained workspace templates from the parts in src/.

.DESCRIPTION
  Each src/<template>/manifest.txt names an output file, token values (set KEY value) and the parts to
  join in order (part <path relative to src/>). Parts are joined with one blank line; {{KEY}} tokens are
  replaced with the manifest's values. Output is UTF-8 without BOM, LF line endings.

  Edit the parts, never the generated files, then run this script. -Check rebuilds in memory and exits 1
  if any generated file differs from what is on disk (run it before committing).

.EXAMPLE
  powershell -File scripts/build-templates.ps1
  powershell -File scripts/build-templates.ps1 -Check
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$src = Join-Path $root 'src'
$utf8 = New-Object System.Text.UTF8Encoding $false
$header = '<!-- Generated by scripts/build-templates.ps1 from the parts in src/. Edit those parts, then run the script; do not edit this file. -->'
$stale = @()

foreach ($manifest in Get-ChildItem $src -Recurse -Filter manifest.txt) {
    $output = $null
    $tokens = @{}
    $parts = @()
    foreach ($line in [IO.File]::ReadAllLines($manifest.FullName, $utf8)) {
        if ($line -match '^\s*(#|$)') { continue }
        if ($line -match '^output\s+(.+)$') { $output = $Matches[1].Trim() }
        elseif ($line -match '^set\s+(\w+)\s+(.+)$') { $tokens[$Matches[1]] = $Matches[2].Trim() }
        elseif ($line -match '^part\s+(.+)$') { $parts += $Matches[1].Trim() }
        else { throw "$($manifest.FullName): unrecognized line '$line'" }
    }
    if (-not $output) { throw "$($manifest.FullName): no output line" }

    $texts = foreach ($part in $parts) {
        $path = Join-Path $src $part
        if (-not (Test-Path $path)) { throw "$($manifest.FullName): missing part $part" }
        ([IO.File]::ReadAllText($path, $utf8) -replace "`r`n", "`n").Trim()
    }
    $text = $header + "`n`n" + ($texts -join "`n`n") + "`n"
    foreach ($key in $tokens.Keys) { $text = $text.Replace("{{$key}}", $tokens[$key]) }
    $left = [regex]::Matches($text, '\{\{\w+\}\}') | ForEach-Object Value | Sort-Object -Unique
    if ($left) { throw "$output`: unreplaced tokens $($left -join ', ')" }

    $target = Join-Path $root $output
    # Compare without line-ending differences: Git may check the files out with CRLF.
    $current = if (Test-Path $target) { [IO.File]::ReadAllText($target, $utf8) -replace "`r`n", "`n" } else { '' }
    if ($current -ceq $text) { Write-Output "unchanged  $output"; continue }
    if ($Check) { $stale += $output; Write-Output "STALE      $output" }
    else { [IO.File]::WriteAllText($target, $text, $utf8); Write-Output "built      $output" }
}

if ($Check -and $stale) { Write-Output 'Generated templates are out of date: run scripts/build-templates.ps1.'; exit 1 }
